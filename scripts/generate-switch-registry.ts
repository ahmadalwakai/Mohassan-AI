import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { reviewedSwitchReaders, type ReviewedReader } from './switch-registry-readers.js';
import { scanSwitchReads, type SwitchReads } from './switch-registry-scan.js';
import { reviewedSourceDigests } from './switch-registry-source-digests.js';

const registryPath = 'apps/server/src/activation-console/switch-registry.generated.ts';
const markdownPath = 'docs/SWITCHES.md';
const sourceUrl = 'https://github.com/ahmadalwakai/Mohassan-AI/blob/29448ae';
const retrieved = '2026-11-27';
const compare = (left: string, right: string) => left < right ? -1 : left > right ? 1 : 0;

interface SwitchReader {
  module: string;
  defaultValue: string;
  parsing: string;
  needsRestart: boolean;
}

interface GeneratedSwitch {
  name: string;
  kind: ReviewedReader['kind'];
  sensitive: boolean;
  modes?: ReviewedReader['modes'];
  readers: readonly SwitchReader[];
}

export function buildSwitchRegistry(
  reads: SwitchReads,
  review: Readonly<Record<string, Readonly<Record<string, ReviewedReader>>>> = reviewedSwitchReaders,
): GeneratedSwitch[] {
  const knownReads = new Set(Object.entries(review)
    .flatMap(([module, entries]) => Object.keys(entries).map(name => `${module} reads ${name}`)));
  const unknown: string[] = [];
  const switches: GeneratedSwitch[] = [];
  for (const [name, modules] of [...reads].sort(([a], [b]) => compare(a, b))) {
    const readers: SwitchReader[] = [];
    let kind: ReviewedReader['kind'] = 'process';
    let sensitive = false;
    let modes: ReviewedReader['modes'];
    for (const module of [...modules.keys()].sort(compare)) {
      const label = `${module} reads ${name}`;
      if (!knownReads.delete(label)) {
        unknown.push(label);
        continue;
      }
      const info = review[module][name];
      readers.push({ module, defaultValue: info.defaultValue, parsing: info.parsing, needsRestart: info.needsRestart });
      if (info.kind === 'feature' || info.kind === 'configuration' && kind === 'process') kind = info.kind;
      sensitive ||= info.sensitive === true;
      if (info.modes) {
        if (modes && JSON.stringify(modes) !== JSON.stringify(info.modes)) {
          throw new Error(`Conflicting current value modes for ${name}`);
        }
        modes = info.modes;
      }
    }
    switches.push({ name, kind, sensitive, ...(modes && { modes }), readers });
  }
  const errors = [
    ...unknown.map(label => `Unknown environment switch reader: ${label}`),
    ...[...knownReads].sort(compare).map(label => `Stale environment switch reader: ${label}`),
  ];
  if (errors.length) throw new Error(errors.join('\n'));
  return switches;
}

function readerFingerprint(reads: SwitchReads): string {
  const lines = [...reads].flatMap(([name, modules]) => [...modules]
    .flatMap(([module, expressions]) => [...expressions].map(expression => JSON.stringify([name, module, expression]))));
  return createHash('sha256').update(lines.sort(compare).join('\n')).digest('hex');
}

export function sourceDigests(reads: SwitchReads): Readonly<Record<string, string>> {
  const modules = new Map<string, string[]>();
  for (const [name, readers] of reads) {
    for (const [module, expressions] of readers) {
      const lines = modules.get(module) ?? [];
      for (const expression of expressions) lines.push(JSON.stringify([name, expression]));
      modules.set(module, lines);
    }
  }
  return Object.fromEntries([...modules].sort(([a], [b]) => compare(a, b)).map(([module, lines]) =>
    [module, createHash('sha256').update(lines.sort(compare).join('\n')).digest('hex')]));
}

export function assertSourceReview(reads: SwitchReads, reviewed = reviewedSourceDigests): void {
  const current = sourceDigests(reads);
  const unsynchronized = Object.entries(current).filter(([module, digest]) => reviewed[module] !== digest);
  const removed = Object.keys(reviewed).filter(module => !Object.hasOwn(current, module));
  if (unsynchronized.length || removed.length) {
    const pending = [
      ...unsynchronized.map(([module, digest]) => `${module} ${digest}`),
      ...removed.map(module => `${module} (no remaining reads)`),
    ];
    throw new Error(['Environment parsing needs review. Check defaults, parsing and restart behavior in',
      'scripts/switch-registry-readers.ts, then update the corresponding source digests.',
      ...pending].join('\n'));
  }
}

function renderTypeScript(switches: readonly GeneratedSwitch[], fingerprint: string): string {
  return `// Generated by scripts/generate-switch-registry.ts from repository source. Do not edit.
// Reviewed source ${sourceUrl} (retrieved ${retrieved}).
// Reader checksum ${fingerprint}.

export interface SwitchReader {
  module: string;
  defaultValue: string;
  parsing: string;
  needsRestart: boolean;
}

export interface GeneratedSwitch {
  name: string;
  kind: 'feature' | 'configuration' | 'process';
  sensitive: boolean;
  modes?: { values: Readonly<Record<string, string>>; otherwise: string };
  readers: readonly SwitchReader[];
}

export const generatedSwitchRegistry: readonly GeneratedSwitch[] = ${JSON.stringify(switches, null, 2)};
`;
}

const cell = (value: string) => value.replaceAll('|', '\\|');

function renderMarkdown(switches: readonly GeneratedSwitch[], fingerprint: string): string {
  const rows = switches.flatMap(entry => entry.readers.map(reader => [
    `\`${entry.name}\``, entry.kind, `[${reader.module}](${sourceUrl}/${reader.module})`, cell(reader.defaultValue),
    cell(reader.parsing), reader.needsRestart ? 'Yes' : 'No', entry.sensitive ? 'Presence' : 'Sanitized value',
  ].join(' | ')));
  return `# Server environment switches

Generated by \`npx tsx scripts/generate-switch-registry.ts\`. The check command is \`npx tsx scripts/generate-switch-registry.ts --check\`.

When a reader changes, review its defaults, parsing and restart behavior in [scripts/switch-registry-readers.ts](../scripts/switch-registry-readers.ts) and update its reviewed digest before regenerating.

The registry scans the server and worker source trees and first-party package source. Feature controls and supporting configuration appear alongside process inputs used by the bootstrap command, test runner or host. Multiple rows mean that different modules read the same setting. Source links point to the production reference commit and were retrieved on ${retrieved}.

**Restart** records whether the reader captures configuration at startup. A setting read on demand can observe a value already present in the running process. Changes to the service environment file still require restarting that service. The table contains code defaults and parsing rules.

<!-- Reader checksum ${fingerprint} -->

| Environment switch | Kind | Reader | Code default | Parsing | Restart | Display |
| --- | --- | --- | --- | --- | --- | --- |
${rows.map(row => `| ${row} |`).join('\n')}
`;
}

export function generateSwitchRegistry(root: string): Readonly<Record<string, string>> {
  const reads = scanSwitchReads(root);
  const switches = buildSwitchRegistry(reads);
  assertSourceReview(reads);
  const fingerprint = readerFingerprint(reads);
  return {
    [registryPath]: renderTypeScript(switches, fingerprint),
    [markdownPath]: renderMarkdown(switches, fingerprint),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const args = process.argv.slice(2);
  const check = args.length === 1 && args[0] === '--check';
  if (!check && args.length) throw new Error('Usage: tsx scripts/generate-switch-registry.ts [--check]');
  for (const [file, generated] of Object.entries(generateSwitchRegistry(root))) {
    const path = resolve(root, file);
    if (!check) writeFileSync(path, generated);
    else if (readFileSync(path, 'utf8') !== generated) throw new Error(`Generated switch registry is out of date: ${file}`);
  }
}
