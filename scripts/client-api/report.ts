import { clientInventory } from './inventory.js';
import type { ClientCall, InventoryRow } from './types.js';

const sourceRepository = 'https://github.com/ahmadalwakai/Mohassan-AI';

function callerLink(call: ClientCall) {
  const target = call.ref
    ? `${sourceRepository}/blob/${call.ref}/${call.file}#L${call.line}`
    : `../${call.file}#L${call.line}`;
  return `[${call.client} ${call.file}:${call.line}](${encodeURI(target)})`;
}

function access(row: InventoryRow) {
  if (row.auth) return row.auth;
  if (row.transport === 'next') return 'Next.js handler';
  if (row.transport === 'external') return 'external service';
  return 'missing';
}

function contract(text: string | undefined, fallback: string) {
  return text ? `\`${text.replaceAll('|', '\\|')}\`` : fallback;
}

function status(row: InventoryRow) {
  const notes = new Set(row.calls.flatMap(call => call.note ? [call.note] : []));
  if (row.server?.note) notes.add(row.server.note);
  if (row.transport === 'fastify' && !row.server) notes.add('Missing Fastify route');
  if (row.transport === 'external') notes.add('Outside the production Fastify app');
  if (row.auth === 'owner') {
    const gate = row.server?.authFile && row.server.authLine
      ? ` ([${row.server.authFile}:${row.server.authLine}](../${row.server.authFile}#L${row.server.authLine}))` : '';
    for (const call of row.calls.filter(call => call.memberVisible)) {
      notes.add(`Member blocked at ${callerLink(call)}${gate}`);
    }
  }
  return [...notes].join('<br>').replaceAll('|', '\\|') || '—';
}

export function renderClientApiContracts(root: string) {
  const rows = clientInventory(root);
  return [
    '# Client API contracts',
    '',
    '<!-- Generated by scripts/client-api-contracts.ts. -->',
    '',
    'Run `npx tsx scripts/client-api-contracts.ts` from the repository root to regenerate this table.',
    'The production comparison started from [29448ae](https://github.com/ahmadalwakai/Mohassan-AI/tree/29448aea3fa10d226ef82ec5bf0a65e723d6ec39) on 2026-11-27.',
    'Fetch the read-only iPhone source with `git fetch origin refs/heads/feat/iphone-store-name:refs/remotes/origin/feat/iphone-store-name` before regenerating or running the inventory test. The iPhone call-site links identify the exact revision.',
    'Web paths use the upstream route behind the Next.js relay. Parameters are shown by route pattern and query strings are omitted.',
    'Access is the minimum workspace role for Fastify routes and the credential class for other services. Endpoint-specific requirements are in Findings.',
    'A shared contract entry names a schema or type in `packages/contracts`. Entries labeled field or item only cover part of the wire shape. No shared contract indicates the absence of a matching package export or a binary, HTML, redirect or empty response.',
    '',
    '| Method | Path | Access | Request contract | Response contract | Call sites | Server | Findings |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(row => {
      const server = row.server ? `[${row.server.file}:${row.server.line}](../${row.server.file}#L${row.server.line})` : '—';
      const noRequest = ['GET', 'HEAD'].includes(row.method) ? 'No shared body' : 'No shared contract';
      return `| ${row.method} | \`${row.path}\` | ${access(row)} | ${contract(row.request, noRequest)} | ${contract(row.response, 'No shared contract')} | ${row.calls.map(callerLink).join('<br>')} | ${server} | ${status(row)} |`;
    }),
    '',
  ].join('\n');
}
