const normalize = (route: string) => route.replace(/\/:[^/]+/g, '/:');
const byRoute = new Map(bindings.map(([route, request, response]) => [normalize(route), { request, response }]));

export function contractBinding(method: string, path: string) {
  return byRoute.get(normalize(method + ' ' + path));
}
